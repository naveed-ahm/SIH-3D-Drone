// Single source of truth lookup helper that seamlessly handles canonical IDs and any legacy aliases
export function getComponentById(id: string | null | undefined): DroneComponent | null {
  if (!id) return null;
  // 1. Exact match
  const exact = DRONE_COMPONENTS.find((c) => c.id === id);
  if (exact) return exact;

  // 2. Normalized match (swap - and _)
  const snake = id.replace(/-/g, '_');
  const kebab = id.replace(/_/g, '-');
  const found = DRONE_COMPONENTS.find((c) => c.id === snake || c.id === kebab);
  if (found) return found;

  // 3. Known specific aliases
  const aliasMap: Record<string, string> = {
    'vtol-motors': 'vtol_motor',
    'vtol_motors': 'vtol_motor',
    'vtol-motor': 'vtol_motor',
    'vtol-props': 'vtol_propeller',
    'vtol_props': 'vtol_propeller',
    'vtol-propeller': 'vtol_propeller',
    'vtol-escs': 'vtol_esc',
    'vtol_escs': 'vtol_esc',
    'esc': 'vtol_esc',
    'escs': 'vtol_esc',
    'servos': 'servo',
    'servo': 'servo',
    'cruise-motor': 'cruise_motor',
    'cruise-prop': 'cruise_propeller',
    'cruise_prop': 'cruise_propeller',
    'cruise-propeller': 'cruise_propeller',
    'cruise-esc': 'cruise_esc',
    'flight-controller': 'flight_controller',
    'gimbal-camera': 'camera_gimbal',
    'gimbal_camera': 'camera_gimbal',
    'camera-gimbal': 'camera_gimbal',
    'camera': 'camera_gimbal',
    'gps-compass': 'gps_compass',
    'gps': 'gps_compass',
    'pitot-airspeed': 'pitot_airspeed',
    'pitot': 'pitot_airspeed',
    'rc-receiver': 'rc_receiver',
    'power-module': 'power_module',
    'left-wing': 'left_wing',
    'right-wing': 'right_wing',
    'landing-gear': 'landing_gear',
    'landing-skid': 'landing_gear',
    'skids': 'landing_gear'
  };

  const mappedId = aliasMap[id] || aliasMap[snake] || aliasMap[kebab];
  if (mappedId) {
    return DRONE_COMPONENTS.find((c) => c.id === mappedId) || null;
  }

  return null;
}

